def normalize_tamil(text: str) -> str:
    """Normalize Tamil text — fix common Whisper misrecognitions."""
    if not text:
        return text

    original = text

    # Apply word-level fixes
    words = text.split()
    fixed_words = []
    for word in words:
        if word in WHISPER_FIXES:
            fixed_words.append(WHISPER_FIXES[word])
        else:
            fixed_words.append(word)

    text = " ".join(fixed_words)

    # Fix common patterns with regex
    # Double spaces
    text = re.sub(r'  +', ' ', text)

    # Missing spaces before Tamil particles
    text = re.sub(r'([.,!?;:])(\s*)', r'\1 ', text)

    # Tamil punctuation normalization
    text = re.sub(r'[।]', '.', text)

    if text != original:
        logger.info(f"[TamilNormalizer] Fixed: '{original[:50]}' → '{text[:50]}'")

    return text.strip()
